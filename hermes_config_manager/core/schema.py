"""Configuration metadata index: types, defaults, descriptions, known values.

Built once (in a worker thread) from ``data/hermes_schema.json`` - generated by
``tools/build_schema.py`` from a dashboard export of an empty Hermes profile
(setting list, order, defaults) and the Hermes runtime source and docs
(descriptions, value sets).  Paths may contain ``*`` wildcards for mapping keys
(``auxiliary.*.provider``) and ``[]`` for list items.

Rules the UI relies on:

* ``enum`` is only present when a closed value set is proven in runtime code.
  Observed values are *suggestions* and never restrict input.
* ``default`` is only reported when a verified source provides it (the
  empty-profile export, else the runtime source).
* Missing descriptions stay missing - nothing is invented.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable

from .paths import MISSING, PathT

DATA_DIR = Path(__file__).resolve().parents[2] / "data"
SCHEMA_FILE = DATA_DIR / "hermes_schema.json"
RUNTIME_SCHEMA = SCHEMA_FILE                      # old name


@dataclass
class FieldMeta:
    path: str                         # pattern, dotted with * and []
    type: str | None = None           # bool|int|float|str|list|map|null|any
    description: str | None = None
    description_source: str | None = None
    enum: list[Any] | None = None     # closed set (runtime-proven)
    enum_source: str | None = None
    observed: list[Any] = field(default_factory=list)   # suggestions, non-exhaustive
    defaults: dict[str, Any] = field(default_factory=dict)   # source label -> value
    status: str = "observed"          # supported | observed-custom | snapshot-only | deprecated
    sources: list[str] = field(default_factory=list)
    secret: bool = False

    @property
    def kind(self) -> str | None:
        return {"bool": "bool", "int": "int", "float": "float", "str": "str", "list": "list",
                "map": "map", "dict": "map", "integer": "int", "number": "float", "string": "str",
                "boolean": "bool", "array": "list", "object": "map"}.get((self.type or "").lower())


def _pattern_key(path: PathT) -> str:
    parts = []
    for p in path:
        parts.append("[]" if isinstance(p, int) else str(p))
    return ".".join(parts).replace(".[]", "[]")


def _to_regex(pattern: str) -> re.Pattern:
    out = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("[]", i):
            out.append(r"\[\]")
            i += 2
        elif pattern[i] == "*":
            out.append(r"[^.\[]+")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


class SchemaIndex:
    def __init__(self, fields: Iterable[FieldMeta] = (), provenance: dict | None = None,
                 extras: dict | None = None) -> None:
        self.provenance = provenance or {}
        self.extras = extras or {}
        self._exact: dict[str, FieldMeta] = {}
        self._wild: list[tuple[re.Pattern, FieldMeta]] = []
        for meta in fields:
            if "*" in meta.path:
                self._wild.append((_to_regex(meta.path), meta))
            else:
                self._exact[meta.path] = meta
        self._lookup_cache: dict[str, FieldMeta | None] = {}

    def __len__(self) -> int:
        return len(self._exact) + len(self._wild)

    @property
    def loaded(self) -> bool:
        return bool(self._exact or self._wild)

    def lookup(self, path: PathT) -> FieldMeta | None:
        key = _pattern_key(path)
        if key in self._lookup_cache:
            return self._lookup_cache[key]
        meta = self._exact.get(key)
        if meta is None:
            for regex, candidate in self._wild:
                if regex.match(key):
                    meta = candidate
                    break
        self._lookup_cache[key] = meta
        return meta

    def children(self, prefix: PathT) -> list[str]:
        """Documented child keys of a mapping (exact paths only)."""
        base = _pattern_key(prefix)
        base = base + "." if base else ""
        out = []
        for key in self._exact:
            if key.startswith(base):
                rest = key[len(base):]
                head = re.split(r"[.\[]", rest, maxsplit=1)[0]
                if head and head not in out:
                    out.append(head)
        return out

    def default(self, path: PathT, prefer: Iterable[str] = ()) -> tuple[Any, str, bool] | None:
        """(value, source label, certain) of the best verified default."""
        meta = self.lookup(path)
        if meta is None or not meta.defaults:
            return None
        for label in prefer:
            for src, value in meta.defaults.items():
                if label and label in src:
                    return value, src, _certain(meta)
        src, value = next(iter(meta.defaults.items()))
        return value, src, _certain(meta)

    def kind(self, path: PathT, value: Any = MISSING) -> str:
        meta = self.lookup(path)
        if meta is not None and meta.enum:
            return "enum"
        if meta is not None and meta.kind:
            return meta.kind
        if value is not MISSING and value is not None:
            return {bool: "bool", int: "int", float: "float", list: "list", dict: "map"}.get(type(value), "str")
        return "str"

    def options(self, path: PathT) -> list[str]:
        meta = self.lookup(path)
        if meta is None:
            return []
        vals = meta.enum if meta.enum else meta.observed
        return [str(v) for v in vals if v is not None and not isinstance(v, (dict, list))]

    def description(self, path: PathT) -> str:
        meta = self.lookup(path)
        if meta is None:
            return "Undocumented key (not in the runtime defaults or the schema snapshot)."
        text = meta.description or "No description available in the metadata sources."
        if meta.description and meta.description_source:
            text += f"\n[{meta.description_source}]"
        if meta.enum:
            text += f"\nAllowed: {', '.join(map(str, meta.enum))}" + (f" [{meta.enum_source}]" if meta.enum_source else "")
        elif meta.observed:
            text += f"\nSeen values (not exhaustive): {', '.join(map(str, meta.observed[:8]))}"
        if meta.status and meta.status != "supported":
            text += f"\nStatus: {meta.status}"
        return text


def _certain(meta: FieldMeta) -> bool:
    values = list(meta.defaults.values())
    if not values:
        return False
    first = json.dumps(values[0], sort_keys=True, default=str)
    agree = all(json.dumps(v, sort_keys=True, default=str) == first for v in values)
    return agree and any(s.startswith("runtime") or "Hermes" in s for s in meta.defaults)


def load_schema(path: Path | None = None) -> SchemaIndex:
    """Load the merged metadata; returns an empty index if unavailable."""
    target = path or RUNTIME_SCHEMA
    try:
        payload = json.loads(target.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return SchemaIndex()
    return schema_from_payload(payload)


def schema_from_payload(payload: dict) -> SchemaIndex:
    """Adapter for ``hermes_schema.json`` (see ``tools/build_schema.py``)."""
    raw_fields = payload.get("fields") or payload.get("keys") or payload.get("paths") or []
    if isinstance(raw_fields, dict):
        raw_fields = [dict(v, path=k) for k, v in raw_fields.items()]
    fields = []
    for raw in raw_fields:
        if not isinstance(raw, dict) or not raw.get("path"):
            continue
        defaults = {}
        d = raw.get("defaults")
        if isinstance(d, dict):
            defaults = dict(d)
        elif "default" in raw and raw.get("default_source") not in (None, "none"):
            defaults = {str(raw.get("default_source")): raw.get("default")}
        desc = raw.get("description")
        if isinstance(desc, dict):
            desc_text, desc_src = desc.get("text"), desc.get("source")
        else:
            desc_text, desc_src = desc, raw.get("description_source")
        enum = raw.get("enum")
        enum_src = None
        if isinstance(enum, dict):
            enum, enum_src = enum.get("values"), enum.get("source") or enum.get("citation")
        observed = raw.get("observed_values") or raw.get("observed") or []
        if isinstance(observed, dict):
            observed = observed.get("values") or []
        note = raw.get("runtime_note")
        if note:
            desc_text = ((desc_text + "\n") if desc_text else "") + f"Runtime: {note}"
            desc_src = desc_src or "runtime source (verified)"
        fields.append(FieldMeta(
            path=str(raw["path"]),
            type=raw.get("type") if isinstance(raw.get("type"), str) else None,
            description=desc_text,
            description_source=desc_src,
            enum=list(enum) if isinstance(enum, list) and enum else None,
            enum_source=enum_src or raw.get("enum_source"),
            observed=list(observed) if isinstance(observed, list) else [],
            defaults=defaults,
            status=str(raw.get("status") or "observed"),
            sources=list(raw.get("sources") or []),
            secret=bool(raw.get("secret")),
        ))
    extras = {k: v for k, v in payload.items() if k not in ("fields", "keys", "paths")}
    return SchemaIndex(fields, payload.get("provenance") or {}, extras)
